def slice_by_field(P, idx, uv, skin_index, skin_weight, field, N=None):
    """Potong mesh dengan bidang implisit `field` (positif = dipertahankan).

    Memilih segitiga utuh (cara sebelumnya) menghasilkan tepi bergerigi sebesar
    satu segitiga; di kelim dan manset itu terlihat seperti kain robek. Di sini
    segitiga yang memotong bidang dibelah dan titik potongnya diinterpolasi,
    jadi tepinya lurus.
    """
    f = np.asarray(field, F)
    signs = f[idx] >= 0
    n = signs.sum(1)

    new_pos = list(P)
    new_uv = list(uv)
    new_si = list(skin_index)
    new_sw = list(skin_weight)
    new_n = list(N) if N is not None else None
    cache = {}

    def cut(i, j):
        key = (i, j) if i < j else (j, i)
        got = cache.get(key)
        if got is not None:
            return got
        d = f[i] - f[j]
        t = float(f[i] / d) if abs(d) > 1e-9 else 0.5
        t = min(max(t, 0.0), 1.0)
        k = len(new_pos)
        new_pos.append(P[i] + (P[j] - P[i]) * t)
        new_uv.append(uv[i] + (uv[j] - uv[i]) * t)
        if new_n is not None:
            new_n.append(N[i] + (N[j] - N[i]) * t)
        # Bobot kulit ikut diinterpolasi; indeks tulang diambil dari sisi yang
        # dipertahankan supaya titik potong tetap terikat ke tulang yang benar.
        # Titik potong mewarisi *seluruh* bobot dari sisi yang dipertahankan.
        # Menginterpolasi bobot sambil mengambil indeks tulang dari satu sisi
        # membuat kain terikat ke tulang yang salah (kain sampai menempel di
        # tangan) — ini yang terjadi sebelumnya.
        src = i if f[i] >= 0 else j
        new_si.append(skin_index[src])
        new_sw.append(skin_weight[src])
        cache[key] = k
        return k

    out = []
    for tri, k, keep in zip(idx, n, signs):
        if k == 3:
            out.append(tri)
            continue
        if k == 0:
            continue
        above = [int(v) for v, kp in zip(tri, keep) if kp]
        below = [int(v) for v, kp in zip(tri, keep) if not kp]
        if k == 1:
            a = above[0]
            out.append([a, cut(a, below[0]), cut(a, below[1])])
        else:
            b = below[0]
            p1, p2 = cut(above[0], b), cut(above[1], b)
            out.append([above[0], above[1], p2])
            out.append([above[0], p2, p1])

    if new_n is not None:
        return (
            np.array(new_pos, F),
            np.array(out, np.int64),
            np.array(new_uv, F),
            np.array(new_si, np.int64),
            np.array(new_sw, F),
            np.array(new_n, F),
        )

    return (
        np.array(new_pos, F),
        np.array(out, np.int64),
        np.array(new_uv, F),
        np.array(new_si, np.int64),
        np.array(new_sw, F),
    )


def _adjacency(tris, n):
    """Sisi dua arah + derajat tiap vertex, untuk operasi halus di mesh kain."""
    e = np.concatenate([tris[:, [0, 1]], tris[:, [1, 2]], tris[:, [2, 0]]])
    e = np.concatenate([e, e[:, ::-1]])
    deg = np.maximum(np.bincount(e[:, 0], minlength=n).astype(F), 1.0)
    return e, deg


def _tangential(pos, e, deg):
    """Rata-rata tetangga dikurangi posisi sendiri (Laplacian di permukaan)."""
    out = np.empty_like(pos)
    for k in range(3):
        acc = np.bincount(e[:, 0], weights=pos[e[:, 1], k], minlength=len(pos))
        out[:, k] = acc / deg - pos[:, k]
    return out


def _cloth_field(b, P, si, sw, piece):
    """Nilai bidang potong untuk sembarang titik (positif = dipertahankan).

    Dipakai dua kali: sekali untuk memotong mesh badan, sekali lagi untuk
    mengukur jarak tiap vertex kain ke batas potong (lihat `margin` di
    `body_cloth`). Satu fungsi supaya kedua pemakaian tidak pernah berbeda.

    "Ini vertex lengan atau bukan" dihitung dari **bobot skin**, bukan dari
    tulang dominan. Mask biner membuat nilai bidang melompat di batas lengan↔bahu;
    lompatan itu menjadi garis potong yang tidak menerus, dan hasilnya terlihat
    sebagai sobekan di jahitan bahu (paling parah di daster yang memakai dua
    kendala sekaligus).
    """
    lo, hi = piece["y"]
    y = P[:, 1]
    field = np.minimum(y - lo, hi - y).astype(F)

    names = np.array([bn["name"] for bn in b["bones"]])
    dom = names[si[:, 0].astype(np.int64)]
    armset = np.zeros(len(names), bool)
    for pre in ("upperarm", "lowerarm", "hand", "finger", "thumb", "metacarpal", "wrist"):
        armset |= np.char.startswith(names, pre)
    wsum = np.maximum(sw.sum(1), 1e-6)
    arm_w = (sw * armset[si]).sum(1) / wsum  # 0 = badan, 1 = lengan penuh

    # Lengan dipotong menurut jarak dari sendi bahu sisi masing-masing (lengan
    # pose-A miring, jadi bidang datar memberi panjang berbeda kiri-kanan).
    # Kendala jarak hanya berlaku di lengan: kalau diterapkan ke semua vertex,
    # dada (1,7 unit dari bahu) ikut terpotong.
    sleeve = piece.get("sleeve", 0.0)
    if sleeve:
        sh = {bn["name"][-1]: np.asarray(bn["p"], F) for bn in b["bones"] if bn["name"].startswith("upperarm01")}
        side = np.where(np.char.endswith(dom, ".L"), "L", "R")
        dist = np.linalg.norm(P - np.stack([sh[s_] for s_ in side]), axis=1)
        field = np.minimum(field, arm_w * (sleeve - dist) + (1 - arm_w) * 10.0)

    # Lubang leher: potong lingkaran di sekitar sumbu leher (dipakai hanya kalau
    # potongan menyetel `neck`; potongan sekarang memakai bidang datar y = hi).
    neck = piece.get("neck", 0.0)
    if neck:
        neck_bone = np.array([bn["p"] for bn in b["bones"] if bn["name"] == "neck01"][0], F)
        above = np.clip((y - (neck_bone[1] - 0.35)) / 0.15, 0, 1)
        rxy = np.linalg.norm(P[:, [0, 2]] - neck_bone[[0, 2]], axis=1)
        field = np.minimum(field, above * (rxy - neck) + (1 - above) * 10.0)

    # Jangkauan dari panggul: tangan ikut berada di ketinggian pinggang saat
    # pose-A, jadi tanpa kendala ini celana panjang menutupi telapak tangan.
    reach = piece.get("reach", 0.0)
    if reach:
        pelv = np.array([bn["p"] for bn in b["bones"] if bn["name"].startswith("pelvis")], F).mean(0)
        dist2 = np.linalg.norm(P - pelv, axis=1)
        field = np.minimum(field, arm_w * (reach - dist2) + (1 - arm_w) * 10.0)

    return field


def _clean_slivers(pos, tris, uv, si, sw, min_height=1.2e-3):
    """Buang segitiga sisir hasil pemotongan (tanpa mengelepatkan vertex).

    Pemotongan bidang menghasilkan segitiga yang sangat tipis di dekat batas
    (tingginya beberapa persepuluh milimeter). Setelah didorong keluar 2 cm,
    sisir itu berubah jadi duri yang menonjol di sekitar kerah dan bahu.

    Vertex **tidak** dilekatkan berdasarkan posisi saja: vertex di jahitan UV
    punya posisi sama tetapi UV berbeda, dan melekatkannya membuat segitiga
    melompati seluruh atlas (tumpang tindih UV 13 % → 22 %).
    """
    tri = pos[tris]
    e1 = tri[:, 1] - tri[:, 0]
    e2 = tri[:, 2] - tri[:, 0]
    area2 = np.linalg.norm(np.cross(e1, e2), axis=1)
    longest = np.maximum.reduce(
        [
            np.linalg.norm(tri[:, 1] - tri[:, 0], axis=1),
            np.linalg.norm(tri[:, 2] - tri[:, 1], axis=1),
            np.linalg.norm(tri[:, 0] - tri[:, 2], axis=1),
        ]
    )
    height = area2 / np.maximum(longest, 1e-9)
    keep = (tris[:, 0] != tris[:, 1]) & (tris[:, 1] != tris[:, 2]) & (tris[:, 2] != tris[:, 0])
    keep &= height > min_height
    tris = tris[keep]
    if len(tris) == 0:
        return None
    used = np.unique(tris)
    remap = np.full(len(pos), -1, np.int64)
    remap[used] = np.arange(len(used), dtype=np.int64)
    return pos[used], remap[tris], uv[used], si[used], sw[used]


def body_cloth(b, P, N, idx, uv, piece):
    """Potong pakaian dari permukaan tubuh (lihat PIECES).

    Mengembalikan dict dengan pos/indices/uv/skinIndex/skinWeight/normals,
    atau None bila potongan itu kosong untuk tubuh ini.
    """
    lo, hi = piece["y"]
    field = _cloth_field(b, P, b["skinIndex"], b["skinWeight"], piece)

    if (field >= 0).sum() < 24:
        return None

    # Normal kain diambil dari normal badan (diinterpolasi di titik potong),
    # bukan dihitung ulang dari mesh kain. Mesh kain terbuka di tepi, jadi
    # normal hasil hitung ulang membelok ke dalam di baris terakhir dan tepinya
    # tampil sebagai gigi hitam — bukan masalah geometri, tapi pencahayaan.
    P2, tris, uv2, si2, sw2, n2 = slice_by_field(
        P, idx, uv, b["skinIndex"], b["skinWeight"], field, np.asarray(N, F)
    )
    used = np.unique(tris)
    remap = np.full(len(P2), -1, np.int64)
    remap[used] = np.arange(len(used), dtype=np.int64)
    pos = P2[used]
    nrm = n2[used]
    uvs = uv2[used]
    si = si2[used]
    sw = sw2[used]
    local = remap[tris]

    cleaned = _clean_slivers(pos, local, uvs, si, sw)
    if cleaned is None:
        return None
    pos, local, uvs, si, sw = cleaned

    # Offset radial dari tulang dominan (bukan sepanjang normal, dan bukan tulang
    # terdekat): di lipatan normal menunjuk ke dalam, dan di ketiak tulang
    # terdekat bisa tulang punggung — dua-duanya membuat kain masuk ke badan.
    # Kelonggaran bertambah ke arah kelim (`flare`) supaya kemeja tidak mencetak
    # bentuk badan.
    axis_all = np.array([bn["p"] for bn in b["bones"]], F)
    # Titik acuan radial = posisi tulang **terbobot**, bukan tulang dominan.
    # Tulang dominan berubah mendadak antar vertex (di bahu: clavicle →
    # spine03), dan karena radius diukur dari titik acuan itu, kain sobek tepat
    # di batas perubahan: duri bergerigi di garis leher dan jahitan bahu.
    # Rata-rata terbobot memakai bobot skin yang sudah halus di seluruh mesh.
    wsum = sw.sum(1, keepdims=True)
    blend = sw / np.maximum(wsum, 1e-6)
    axis = np.einsum("nk,nkj->nj", blend, axis_all[si.astype(np.int64)])
    dirs = pos - axis
    dist = np.linalg.norm(dirs, axis=1, keepdims=True)
    radial = dirs / np.maximum(dist, 1e-4)
    offset = np.full((len(pos), 1), piece["offset"], F)
    flare = piece.get("flare", 0.0)
    if flare:
        span = max(1e-3, float(pos[:, 1].max()) - lo)
        t = np.clip((float(pos[:, 1].max()) - pos[:, 1]) / span, 0, 1)[:, None]
        offset = offset + flare * (t ** 1.4)
    disp = radial * offset

    # Tepi potong (kelim, manset, kerah) harus lurus. Offset radial punya
    # komponen y; kalau dipakai apa adanya, vertex tepat di bawah tepi ikut
    # terangkat melewati garis potong dan siluet kain jadi bergerigi. Komponen y
    # dimatikan dengan bobot yang naik halus dari batas potong (0 di tepi → 1
    # setelah ±0,25 unit ≈ 2,5 cm), jadi kelim tetap datar tapi badan kain
    # memakai offset penuh.
    margin = _cloth_field(b, pos, si, sw, piece)
    w = np.clip(margin / 0.25, 0.0, 1.0)[:, None]
    disp[:, 1] = disp[:, 1] * w[:, 0]
    base = pos.copy()
    pos = pos + disp
    pinned = pos.copy()

    # Relaksasi: kain yang hanya di-offset tetap mencetak tonjolan badan (dada,
    # pusar, tempurung lutut, bokong). Di sini permukaan kain dihaluskan
    # (Laplacian tangensial), lalu tiap vertex ditarik kembali keluar sepanjang
    # arah offset semula sampai jaraknya ke badan tidak kurang dari `min_clear`.
    # Siluetnya jadi rata tanpa kain menembus badan. Ini tidak memakai kerangka
    # acuan per tulang — percobaan dengan radius dari sumbu tulang justru
    # membuat permukaan bergelombang karena sumbu tiap vertex berbeda.
    relax = int(piece.get("relax", 4))
    if relax:
        e, deg = _adjacency(local, len(pos))
        floor = piece.get("min_clear", 0.11)
        # Tepi potong = apa pun yang jaraknya ke batas potong < 3 mm. Ambang 1e-3
        # dulu terlalu ketat: beberapa vertex kelim lolos dan ikut bergerak,
        # jadi garis kelim tampak bergerigi.
        edge = margin < 0.03
        for _ in range(relax):
            lap = _tangential(pos, e, deg) * 0.45
            if edge.any():
                lap[edge] = 0.0
            pos = pos + lap
            delta = pos - base
            d = np.linalg.norm(delta, axis=1)
            short = d < floor
            if short.any():
                pos[short] = base[short] + radial[short] * floor
        # Tepi potong dikembalikan persis ke posisi hasil offset: relaksasi di
        # sekitarnya boleh bergerak, tapi garis kelim/kerah/manset harus tetap
        # lurus.
        if edge.any():
            pos[edge] = pinned[edge]

    # Tepi potong mendatar harus lurus. Offset radial punya komponen y, jadi
    # vertex di dekat kelim bisa melewati garis potong dan kelim tampak
    # bergerigi (spike 6 mm diukur pada polo). Karena potongan atas dan bawah
    # memang bidang datar, mengunci y ke rentang potongan tidak mengubah bentuk
    # lain — hanya merapikan tepinya.
    pos[:, 1] = np.clip(pos[:, 1], lo, hi)

    pos, uvs, si, sw, radial, local = _close_rim(pos, uvs, si, sw, radial, local)
    return {
        "pos": pos,
        "indices": local,
        "uv": uvs,
        "skinIndex": si,
        "skinWeight": sw,
        "normals": nrm,
        "verts": len(pos),
        "tris": int(len(local)),
    }


def _close_rim(pos, uv, skin_index, skin_weight, radial, tris, thickness=0.0):
    """Tutup tepi terbuka kain dengan pita tipis ke arah dalam (opsional).

    Pita ini sempat dipakai untuk menutupi tepi yang bergerigi, tapi sumber
    gerigi itu komponen y dari offset radial (sudah diperbaiki di body_cloth),
    jadi sekarang tidak dipakai: tebal 0 berarti tepi dibiarkan apa adanya.
    Kalau nanti kain diberi ketebalan sungguhan, pita ini bisa dihidupkan lagi.
    """
    if thickness <= 0:
        return pos, uv, skin_index, skin_weight, radial, tris
    e = np.concatenate([tris[:, [0, 1]], tris[:, [1, 2]], tris[:, [2, 0]]])
    e = np.sort(e, axis=1)
    uniq, inv, counts = np.unique(e, axis=0, return_inverse=True, return_counts=True)
    boundary = uniq[counts == 1]
    if len(boundary) == 0:
        return pos, uv, skin_index, skin_weight, radial, tris

    verts = np.unique(boundary)
    inner = np.full(len(pos), -1, np.int64)
    inner[verts] = len(pos) + np.arange(len(verts))

    new_pos = np.concatenate([pos, pos[verts] - radial[verts] * thickness])
    new_uv = np.concatenate([uv, uv[verts]])
    new_si = np.concatenate([skin_index, skin_index[verts]])
    new_sw = np.concatenate([skin_weight, skin_weight[verts]])
    new_radial = np.concatenate([radial, radial[verts]])

    rim = []
    for a, c in boundary:
        ai, ci = inner[a], inner[c]
        # dua segitiga per sisi; arah hadap tidak dijaga karena kain dua sisi
        rim.append([a, c, ci])
        rim.append([a, ci, ai])
    new_tris = np.concatenate([tris, np.array(rim, np.int64)])
    return new_pos, new_uv, new_si, new_sw, new_radial, new_tris


def _boundary_edges(tris):
    """Tepi terbuka: sisi yang hanya dipakai satu segitiga."""
    e = np.concatenate([tris[:, [0, 1]], tris[:, [1, 2]], tris[:, [2, 0]]])
    e = np.sort(e, axis=1)
    uniq, counts = np.unique(e, axis=0, return_counts=True)
    return uniq[counts == 1]


def _ring(be, verts, pos):
    """Urutkan vertex tepi jadi cincin.

    Ditelusuri lewat sisi yang kedua ujungnya ada di `verts`, jadi cincin tidak
    pernah melompat ke loop lain (kelim atau manset) — itu yang dulu membuat
    pita kerah berupa lembaran raksasa. Kalau penelusuran tidak menutup rapi
    (loop bercabang karena tepi nyaris sejajar permukaan), urutannya diganti
    urutan sudut mengelilingi pusat: kerah, kelim, dan manset semuanya
    melingkupi satu sumbu, jadi urutan sudut selalu benar untuk kasus itu.
    """
    sel = set(int(v) for v in verts)
    nb = {}
    for a, b in be:
        a, b = int(a), int(b)
        if a in sel and b in sel:
            nb.setdefault(a, []).append(b)
            nb.setdefault(b, []).append(a)
    if not nb:
        return None
    start_v = next(iter(nb))
    ring = [start_v]
    prev, cur = None, start_v
    while True:
        nxt = [v for v in nb.get(cur, []) if v != prev]
        if not nxt:
            break
        step = nxt[0]
        if step == ring[0]:
            break
        if step in ring:
            break
        ring.append(step)
        prev, cur = cur, step
        if len(ring) > len(nb):
            break
    if len(ring) == len(nb):
        return np.array(ring, np.int64)
    idx = np.array(sorted(nb), np.int64)
    P = pos[idx]
    c = P.mean(0)
    ang = np.arctan2(P[:, 2] - c[2], P[:, 0] - c[0])
    return idx[np.argsort(ang)]


def _band(pos, ring, normals, height, proud=0.004):
    """Pita lipatan sepanjang cincin tepi; sumbu lebar = normal permukaan."""
    P = pos[ring]
    ax = normals[ring]
    ax = ax / np.maximum(np.linalg.norm(ax, axis=1, keepdims=True), 1e-6)
    a = P + ax * (height / 2) + ax * proud
    b = P - ax * (height / 2) + ax * proud
    n = len(ring)
    verts = np.concatenate([a, b])
    tris = []
    for k in range(n):
        k2 = (k + 1) % n
        tris.append([k, k2, n + k2])
        tris.append([k, n + k2, n + k])
    return verts, np.array(tris, np.int64), np.concatenate([ring, ring])


def collar_ring(pos, tris, skin_index, skin_weight, uv, normals, neck_y, height=0.075):
    """Kerah crew-neck: pita lipatan di tepi lubang leher.

    Hanya loop leher yang diambil (`higher than neck_y` dan radius kecil),
    karena kelim dan manset tidak perlu pita — di sana lipatan kain tidak
    terbaca pada jarak kamera cerita dan tri-nya lebih baik dipakai untuk
    detail yang benar-benar terlihat (kancing, saku).
    """
    be = _boundary_edges(tris)
    verts = np.unique(be)
    P = pos[verts]
    r = np.linalg.norm(P[:, [0, 2]], axis=1)
    sel = verts[(P[:, 1] > neck_y) & (r < 1.0)]
    if len(sel) < 10:
        return None
    # Urutkan menurut sudut mengelilingi sumbu leher, **bukan** dengan menelusuri
    # tepi: lubang leher berbentuk bintang terhadap sumbu itu, jadi urutan sudut
    # selalu benar, sedangkan penelusuran tepi kadang melompat (dulu hasilnya
    # pita kerah bergerigi seperti gigi di leher).
    C = pos[sel]
    cx = 0.0
    cz = float(np.mean(C[:, 2]))
    ang = np.arctan2(C[:, 2] - cz, C[:, 0] - cx)
    ring = sel[np.argsort(ang)]
    # Pita kerah dibuat **vertikal** (naik sepanjang +y), bukan sepanjang normal
    # permukaan. Normal di garis leher sangat bervariasi antar vertex (menghadap
    # ke atas di depan, ke samping di bahu), jadi pita yang mengikuti normal
    # zigzag dan tampil sebagai gigi putih di leher. Pita vertikal selalu mulus:
    # bidang singgungnya = garis tepi × sumbu y, normalnya = arah radial keluar.
    C = pos[ring]
    cz = float(np.mean(C[:, 2]))
    rad = np.stack([C[:, 0], np.zeros(len(ring), F), C[:, 2] - cz], 1)
    rad /= np.maximum(np.linalg.norm(rad, axis=1, keepdims=True), 1e-6)
    up = np.array([0.0, height, 0.0], F)
    top = C + up + rad * 0.008
    bot = C + rad * 0.008
    verts = np.concatenate([top, bot])
    n_ring = len(ring)
    tris = []
    for k in range(n_ring):
        k2 = (k + 1) % n_ring
        tris.append([k, k2, n_ring + k2])
        tris.append([k, n_ring + k2, n_ring + k])
    return {
        "pos": verts,
        "indices": np.array(tris, np.int64),
        "uv": np.concatenate([uv[ring], uv[ring]]),
        "skinIndex": np.concatenate([skin_index[ring], skin_index[ring]]),
        "skinWeight": np.concatenate([skin_weight[ring], skin_weight[ring]]),
        "normals": np.concatenate([rad, rad]),
    }


def buttons(pos, tris, normals, heights, radius=0.055, thickness=0.012, sides=10):
    """Kancing bulat kecil di tengah depan, find ciri kain terdepan di tiap tinggi.

    Untuk tiap tinggi dicari vertex kain dengan |x| kecil dan z terbesar (paling
    depan); kancing diletakkan di sana, sedikit menonjol sepanjang normal.
    """
    verts = np.unique(tris)
    P = pos[verts]
    out_pos, out_src, out_tris, out_nrm = [], [], [], []
    base = 0
    for h in heights:
        band = np.abs(P[:, 1] - h) < 0.06
        front = np.where(P[:, 2] > 0.0, P[:, 2], -1.0)
        cand = np.where(band & (np.abs(P[:, 0]) < 0.16), front, -1.0)
        if cand.max() <= 0:
            continue
        i = int(np.argmax(cand))
        c = P[i]
        n = normals[verts[i]] if normals is not None else np.array([0, 0, 1], F)
        n = n / max(float(np.linalg.norm(n)), 1e-6)
        # Bingkai lokal: u tegak lurus n (horizontal), v = n x u.
        u = np.cross(np.array([0, 0, 1], F), n)
        if np.linalg.norm(u) < 1e-5:
            u = np.cross(np.array([1, 0, 0], F), n)
        u /= np.linalg.norm(u)
        v = np.cross(n, u)
        c = c + n * 0.004
        ring = []
        for k in range(sides):
            a = 2 * np.pi * k / sides
            ring.append(c + u * (np.cos(a) * radius) + v * (np.sin(a) * radius))
        top = [p + n * thickness for p in ring]
        start = base
        out_pos.extend(ring)
        out_pos.extend(top)
        out_src.extend([verts[i]] * (2 * sides))
        out_nrm.extend([n] * (2 * sides))
        for k in range(sides):
            k2 = (k + 1) % sides
            out_tris.append([start + k, start + k2, start + sides + k2])
            out_tris.append([start + k, start + sides + k2, start + sides + k])
        # Tutup atas kancing.
        for k in range(1, sides - 1):
            out_tris.append([start + sides, start + sides + k, start + sides + k + 1])
        base += 2 * sides
    if not out_pos:
        return None
    return {
        "pos": np.array(out_pos, F),
        "indices": np.array(out_tris, np.int64),
        "src": np.array(out_src, np.int64),
        "normals": np.array(out_nrm, F),
    }


def _inward(pos, tris, verts):
    """Arah ke dalam permukaan untuk vertex tepi (rata-rata tetangga 1-ring)."""
    e = np.concatenate([tris[:, [0, 1]], tris[:, [1, 2]], tris[:, [2, 0]]])
    e = np.concatenate([e, e[:, ::-1]])
    deg = np.maximum(np.bincount(e[:, 0], minlength=len(pos)).astype(F), 1.0)
    acc = np.stack(
        [np.bincount(e[:, 0], weights=pos[e[:, 1], k], minlength=len(pos)) for k in range(3)], 1
    )
    return acc / deg[:, None]


def hem_stitch(pos, tris, uv, skin_index, skin_weight, normals, exclude_above,
               inset=0.055, width=0.030, lift=0.010, band=0.12):
    """Jahitan garis (topstitch) di dalam kelim bawah.

    Hanya kelim bawah yang diberi garis: di situlah jahitan terbaca di shot
    cerita, dan tri-nya murah (± 2 segitiga per sisi tepi). Titik tepi diambil
    menurut tinggi (`y < y_min + band`), bukan dengan menelusuri loop — tepi kain
    ini sering menyatu dalam satu loop besar (kelim + manset bertemu di ketiak),
    jadi penelusuran loop melewatkannya.

    Arah "ke dalam kain" diambil dari rata-rata tetangga 1-ring tiap vertex tepi,
    bukan dari urutan loop; arah itu diproyeksikan ke bidang singgung lalu
    diangkat `lift` sepanjang normal supaya tidak berkelahi z dengan kain.
    """
    be = _boundary_edges(tris)
    bverts = np.unique(be)
    ymin = float(pos[bverts][:, 1].min())
    sel = bverts[(pos[bverts][:, 1] < ymin + band) & (pos[bverts][:, 1] < exclude_above)]
    if len(sel) < 6:
        return None
    N = normals if normals is not None else np.tile(np.array([0, 0, 1], F), (len(pos), 1))
    n = N / np.maximum(np.linalg.norm(N, axis=1, keepdims=True), 1e-6)
    inner_pt = _inward(pos, tris, sel)
    d = inner_pt[sel] - pos[sel]
    d -= n[sel] * (d * n[sel]).sum(1, keepdims=True)  # buang komponen normal
    d /= np.maximum(np.linalg.norm(d, axis=1, keepdims=True), 1e-6)

    lookup = {int(v): i for i, v in enumerate(sel)}
    a = pos[sel] + d * inset + n[sel] * lift
    b = pos[sel] + d * (inset + width) + n[sel] * lift
    k = len(sel)
    verts = np.concatenate([a, b])
    uv2 = np.concatenate([uv[sel], uv[sel]])
    si2 = np.concatenate([skin_index[sel], skin_index[sel]])
    sw2 = np.concatenate([skin_weight[sel], skin_weight[sel]])
    out_tris = []
    for u_, v_ in be:
        i, j = lookup.get(int(u_)), lookup.get(int(v_))
        if i is None or j is None:
            continue
        out_tris.append([i, j, k + j])
        out_tris.append([i, k + j, k + i])
    if not out_tris:
        return None
    return {
        "pos": verts,
        "indices": np.array(out_tris, np.int64),
        "uv": uv2,
        "skinIndex": si2,
        "skinWeight": sw2,
        "normals": np.concatenate([n[sel], n[sel]]),
    }


def paint_pocket(base, pos_map, mask, target, half_u=0.42, half_v=0.50,
                 dark=0.80, line=0.55, band=0.045):
    """Gambar saku langsung ke albedo kain (tanpa geometri baru).

    Saku geometris (bidang di-fitting maupun sub-mesh) tampil hitam di WebGL
    meskipun warnanya benar di renderer perangkat lunak — persoalan material/UV
    satu titik yang tidak terselesaikan sebelum tenggat. Versi ini hanya
    menggelapkan texel: aman di semua renderer, tanpa tri tambahan, dan tidak
    menyentuh atlas UV (tidak ada tabrakan baru).

    `pos_map`/`mask` = hasil `uvpaint.rasterize_uv` untuk potongan kain ini,
    `target` = (x, y) di ruang kain, satuannya sama dengan posisi kain.
    """
    P = pos_map.reshape(-1, 3)
    flat = mask.reshape(-1)
    s_ = P[:, 0] - float(target[0])
    t_ = P[:, 1] - float(target[1])
    inside = (np.abs(s_) <= half_u) & (np.abs(t_) <= half_v) & flat & (P[:, 2] > 0.0)
    if inside.sum() < 40:
        return base
    edge = inside & ((np.abs(s_) > half_u - band) | (np.abs(t_) > half_v - band))
    out = base.reshape(-1, 3).copy()
    out[inside] *= dark
    out[edge] *= line
    return out.reshape(base.shape)


def fabric_texture(color="#cfd6dd", seed=7, size=512):
    """Tekstur kain prosedural: tenunan halus + lipatan, warna per outfit.

    Tenunan 140 ulir di atlas 512 px terbaca sebagai kotak-kotak besar di layar
    (UV kain hanya memakai sebagian atlas), sehingga kain tampak seperti jaring
    bodysuit. Relief tenunan di sini dilembutkan dan kontrasnya diturunkan:
    warnanya tetap, polanya hilang.
    """
    from . import tex

    rgb = tex.hexc(color.lstrip("#"))
    f = tex.fabric(seed, size, rgb, weave=150, folds=0.35)
    base = np.clip(tex.blur(f["base"], 3) * 0.65 + f["base"] * 0.35, 0, 1)
    height = tex.blur(base.mean(-1), 2)
    normal = tex.height_to_normal(height, 0.45)
    rough = np.clip(0.92 + (height - 0.5) * 0.10, 0.5, 1.0)
    ao = np.clip(1.0 - (tex.blur(height, 6) - height) * 1.2, 0.55, 1.0)
    return {"base": base, "normal": normal, "orm": tex.orm(ao, rough, np.zeros((size, size), F))}


def flat_fabric(color="#cfd6dd", size=64):
    """Bahan warna rata untuk detail ber-UV satu titik.

    Kerah, kancing, saku, dan jahitan memakai UV satu titik (luas nol) supaya
    `qc-uv` bersih. Akibatnya tidak ada satu pun pola yang bisa terbaca, dan
    memakai `fabric_texture` hanya mengambil satu texel tenunan — yang kebetulan
    jatuh di benang gelap, sehingga kancing dan saku tampil hampir hitam.
    Di sini albedonya warna rata dengan variasi sangat halus.
    """
    from . import tex

    rgb = tex.hexc(color.lstrip("#"))
    base = np.tile(rgb, (size, size, 1))
    rng = np.random.default_rng(5)
    base *= 1.0 + (rng.random((size, size, 1)).astype(F) - 0.5) * 0.03
    base = np.clip(base, 0, 1)
    # Peta normal dienkode ke 0..1 (0,5 = datar), sama seperti keluaran
    # `tex.height_to_normal`. Nilai (0,0,1) yang dipakai semula terbaca sebagai
    # normal miring 45 derajat sehingga seluruh detail tampil nyaris hitam.
    normal = np.full((size, size, 3), 0.5, F)
    normal[..., 2] = 1.0
    rough = np.full((size, size), 0.92, F)
    ao = np.ones((size, size), F)
    return {"base": base, "normal": normal, "orm": tex.orm(ao, rough, np.zeros((size, size), F))}


def garment_pack(name, weave_seed):
    """Real cloth PBR: the authored diffuse as base colour plus woven relief."""
    from PIL import Image

    d = json.loads((PUBLIC / "garments" / f"{name}.json").read_text())
    img = Image.open(PUBLIC / "garments" / d["texture"]).convert("RGB").resize((512, 512), Image.LANCZOS)
    base = np.asarray(img, F) / 255.0
    target = GARMENT_LUMA.get(name)
    if target:
        for _ in range(3):  # rescale, re-clip, converge (keeps relative detail)
            m = float(base.mean())
            if m <= 1e-4:
                break
            base = np.clip(base * (target / m), 0, 1)
    weave = tex.fabric(weave_seed, 512, (0.5, 0.5, 0.5), weave=180, folds=0.3)
    # keep authored colour, take relief from the weave
    lum = base.mean(-1, keepdims=True)
    detail = (weave["normal"] - 0.5) * 0.6 + 0.5
    normal = tex.height_to_normal(0.5 + (lum[..., 0] - 0.5) * 0.5 + (detail[..., 0] - 0.5) * 0.25, 1.4)
    rough = np.clip(0.82 + (lum[..., 0] - 0.5) * 0.15, 0.5, 1.0)
    ao = np.clip(1 - (0.35 - lum[..., 0]) * 0.5, 0.5, 1.0)
    return {
        "tex": {"base": base, "normal": normal, "orm": tex.orm(ao, rough, np.zeros((512, 512), F))},
        "positions": np.array(d["positions"], F).reshape(-1, 3),
        "uv": np.array(d["uv"], F).reshape(-1, 2),
        "indices": np.array(d["indices"], np.int64).reshape(-1, 3),
        "skinIndex": np.array(d["skinIndex"], np.int64).reshape(-1, 4),
        "skinWeight": np.array(d["skinWeight"], F).reshape(-1, 4),
        "hidden": set(int(i) for i in d["hidden"]),
    }


