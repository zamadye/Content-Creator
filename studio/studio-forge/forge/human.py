# --------------------------------------------------------------- proportions
# Landmark MakeHuman (satuan unit, alas kaki di -8.168, ubun-ubun 8.49).
Y_FEET, Y_HIP, Y_NECK, Y_TOP = -8.168, 0.60, 5.95, 8.49
TOTAL = Y_TOP - Y_FEET

# Profil proporsi = (paha+kaki, torso, kepala) sebagai fraksi tinggi badan,
# plus faktor radial untuk badan (anak-anak lebih ramping, kepala tidak menyusut).
PROFILES = {
    "dewasa":  (0.527, 0.321, 0.152, 1.00),
    "lansia":  (0.510, 0.318, 0.172, 1.00),
    "remaja":  (0.505, 0.325, 0.170, 0.96),
    "anak":    (0.450, 0.340, 0.210, 0.90),
    "anak-besar": (0.470, 0.335, 0.195, 0.93),
    "balita":  (0.415, 0.340, 0.245, 0.86),
}


def _band_scales(profile):
    leg_f, torso_f, head_f, radial = profile
    s_leg = leg_f * TOTAL / (Y_HIP - Y_FEET)
    s_torso = torso_f * TOTAL / (Y_NECK - Y_HIP)
    s_head = head_f * TOTAL / (Y_TOP - Y_NECK)
    return s_leg, s_torso, s_head, radial


def proportion_curve(profile):
    """Kurva y → (y', radial) yang sama untuk mesh, pakaian, dan tulang."""
    s_leg, s_torso, s_head, radial = _band_scales(profile)
    # Growing only in Y stretches a child's eye sockets and skull vertically.
    child = profile in (PROFILES["anak"], PROFILES["anak-besar"], PROFILES["balita"])
    head_radius = s_head if child else 1.0

    def fn(y):
        y = np.asarray(y, F)
        out = np.where(
            y <= Y_HIP,
            Y_FEET + (y - Y_FEET) * s_leg,
            np.where(
                y <= Y_NECK,
                Y_FEET + (Y_HIP - Y_FEET) * s_leg + (y - Y_HIP) * s_torso,
                Y_FEET
                + (Y_HIP - Y_FEET) * s_leg
                + (Y_NECK - Y_HIP) * s_torso
                + (y - Y_NECK) * s_head,
            ),
        )
        # radial: badan mengikuti profil, kepala penuh (anak = kepala besar)
        t = np.clip((y - (Y_NECK - 0.9)) / 0.9, 0, 1)
        r = radial + (1.0 - radial) * t
        # Keep the additional head width above the neckline so sleeves and
        # shoulder joints keep their original span.
        r += (head_radius - 1.0) * smoothstep(np.clip((y - Y_NECK) / 0.50, 0, 1))
        return out.astype(F), r.astype(F)

    return fn


def apply_proportions(P, profile):
    """Regangkan pita vertikal (kaki/torso/kepala) pada mesh atau pakaian."""
    fn = proportion_curve(profile)
    P = np.asarray(P, F)
    y2, r = fn(P[:, 1])
    out = P.copy()
    out[:, 1] = y2
    out[:, 0] *= r
    out[:, 2] *= r
    return out


def proportion_bones(bones, profile):
    fn = proportion_curve(profile)
    out = []
    for b in bones:
        p = np.asarray(b["p"], F)
        y2, r = fn(np.array([p[1]], F))
        q = np.array([p[0] * float(r[0]), float(y2[0]), p[2] * float(r[0])], F)
        out.append({**b, "p": q})
    return out


def base_pose(arm_drop=0.34, finger_curl=0.55, hands_forward=0.0):
    # The authored rig rests in an A-pose (~49° below horizontal), so arm_drop is an
    # *additional* drop from there. large values swing the arms across the torso.
    p = {}
    p["upperarm01.L"] = [hands_forward, 0, -arm_drop]
    p["upperarm01.R"] = [hands_forward, 0, arm_drop]
    p["lowerarm01.L"] = [-0.18, 0.0, -0.10]
    p["lowerarm01.R"] = [-0.18, 0.0, 0.10]
    for side, s in (("L", 1), ("R", -1)):
        for f in ("finger1", "finger2", "finger3", "finger4", "finger5"):
            for j, curl in ((1, 0.55), (2, 0.75), (3, 0.5)):
                p[f"{f}-{j}.{side}"] = [0, 0, -s * curl * finger_curl]
        p[f"finger1-1.{side}"][0] = -s * 0.1
    p["spine01"] = [0.02, 0, 0]
    p["neck01"] = [-0.04, 0, 0]
    return p


def add(pose, bone, rx=0, ry=0, rz=0):
    cur = pose.setdefault(bone, [0.0, 0.0, 0.0])
    cur[0] += rx
    cur[1] += ry
    cur[2] += rz


def mix(a, b, t):
    out = {}
    for k in set(a) | set(b):
        va = a.get(k, [0, 0, 0])
        vb = b.get(k, [0, 0, 0])
        out[k] = [va[i] + (vb[i] - va[i]) * t for i in range(3)]
    return out


CLIPS = {}


def clip(name, frames, loop=True):
    def deco(fn):
        CLIPS[name] = {"frames": frames, "fn": fn, "loop": loop}
        return fn

    return deco


TAU = 2.0 * math.pi


def clamp01(x):
    return 0.0 if x < 0 else (1.0 if x > 1 else x)


def ease(x):
    u = clamp01(x)
    return u * u * (3.0 - 2.0 * u)


def hold_wave(phase):
    """Ayunan dengan *dwell* di ujung: berhenti sejenak lalu berbalik."""
    s = math.sin(phase)
    return math.copysign(abs(s) ** 0.55, s)


def pulse(t, center, width):
    """Pulsa 0..1 dengan naik cepat lalu turun pelan (aksi → settle)."""
    d = abs(t - center)
    if d >= width:
        return 0.0
    return ease(1.0 - d / width)


def blink_curve(t, centers, dur=0.075):
    best = 0.0
    for c in centers:
        d = abs(t - c)
        if d < dur:
            best = max(best, ease(1.0 - d / dur))
    return best


def blink_scales(t, centers, mouth=0.0):
    """Kedip (dan bukaan mulut) lewat skala — konvensi rig: `eye.*.scale.y`."""
    b = blink_curve(t, centers)
    out = {
        "eye.L": (1.0, 1.0 - 0.95 * b, 1.0),
        "eye.R": (1.0, 1.0 - 0.95 * b, 1.0),
    }
    if mouth > 0.0:
        out["oris05"] = (1.0 - 0.16 * mouth, 0.19 + 0.91 * mouth, 1.0)
    return out


