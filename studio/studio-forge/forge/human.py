# --------------------------------------------------------------------- shaping
def _elen(P, c, r):
    return np.sqrt((((P - np.asarray(c, F)) / np.asarray(r, F)) ** 2).sum(1))


def _w(P, c, r, soft=0.55):
    d = _elen(P, c, r)
    return 1.0 - smoothstep((d - (1 - soft)) / max(soft, 1e-6))


def shape(P, v):
    """Ellipsoidal deformers. `v` holds multipliers/biases per anatomical region."""
    P = np.array(P, F, copy=True)
    sx = np.sign(P[:, 0])
    # shoulders / chest width
    P[:, 0] += sx * _w(P, (0, 5.05, 0.15), (1.35, 0.60, 0.85)) * v.get("shoulder", 0.0) * 0.22
    # rib depth
    P[:, 2] += _w(P, (0, 4.30, 0.10), (1.30, 0.95, 0.95)) * v.get("chest", 0.0) * 0.16
    # belly
    P[:, 2] += _w(P, (0, 2.35, 0.55), (0.75, 0.80, 0.55)) * v.get("belly", 0.0) * 0.30
    # waist
    P[:, 0] -= sx * _w(P, (0, 2.80, 0.10), (0.90, 0.60, 0.70)) * v.get("waist", 0.0) * 0.10
    # hips
    P[:, 0] += sx * _w(P, (0, 1.10, 0.10), (0.85, 0.55, 0.80)) * v.get("hip", 0.0) * 0.20
    # glutes
    P[:, 2] -= _w(P, (0, 1.00, -0.55), (0.75, 0.55, 0.55)) * v.get("glute", 0.0) * 0.20
    # limb thickness (arms below shoulder, legs below hip)
    limbs = (np.abs(P[:, 0]) > 1.25) | (P[:, 1] < 0.3)
    limb_w = _w(P, (0, 2.0, 0.0), (5.2, 8.5, 5.2), 0.2) * limbs
    radial = np.stack([P[:, 0] - np.clip(P[:, 0], -0.85, 0.85), P[:, 1] - np.clip(P[:, 1], -6.6, 3.2), P[:, 2]], 1)
    P += radial / np.maximum(np.linalg.norm(radial, axis=1, keepdims=True), 1e-6) * (limb_w * v.get("limb", 0.0) * 0.10)[:, None]
    # neck
    P[:, 0] += sx * _w(P, (0, 5.85, 0.05), (0.45, 0.55, 0.45)) * v.get("neck", 0.0) * 0.10
    P[:, 2] += _w(P, (0, 5.85, 0.05), (0.45, 0.55, 0.45)) * v.get("neck_fwd", 0.0) * 0.10
    # ---- head
    head = P[:, 1] > 6.35
    P[:, 0] += sx * _w(P, (0, 7.55, 0.55), (0.95, 1.05, 1.15)) * v.get("skull_w", 0.0) * 0.16
    P[:, 1] += _w(P, (0, 7.90, 0.30), (0.95, 0.85, 1.10)) * v.get("skull_h", 0.0) * 0.16
    P[:, 2] += _w(P, (0, 7.90, 0.20), (0.95, 0.80, 1.15)) * v.get("skull_d", 0.0) * 0.14
    P[:, 0] += sx * _w(P, (0, 6.75, 1.05), (0.75, 0.55, 0.60)) * v.get("jaw_w", 0.0) * 0.20
    P[:, 1] -= _w(P, (0, 6.35, 1.20), (0.45, 0.30, 0.45)) * v.get("chin_drop", 0.0) * 0.16
    P[:, 2] += _w(P, (0, 6.32, 1.42), (0.42, 0.30, 0.40)) * v.get("chin_fwd", 0.0) * 0.14
    P[:, 2] += _w(P, (0, 7.02, 1.35), (0.85, 0.32, 0.45)) * v.get("cheek", 0.0) * 0.14
    P[:, 2] += _w(P, (0, 7.45, 1.32), (0.62, 0.14, 0.35)) * v.get("brow", 0.0) * 0.12
    P[:, 0] += sx * _w(P, (0.09, 6.95, 1.62), (0.16, 0.22, 0.18)) * v.get("nose_w", 0.0) * 0.10
    P[:, 2] += _w(P, (0, 6.96, 1.68), (0.14, 0.22, 0.22)) * v.get("nose_l", 0.0) * 0.10
    P[:, 1] -= _w(P, (0, 6.52, 1.55), (0.30, 0.12, 0.25)) * v.get("lip_full", 0.0) * 0.06
    P[:, 2] += _w(P, (0, 6.52, 1.56), (0.30, 0.12, 0.25)) * v.get("lip_fwd", 0.0) * 0.05
    P[:, 0] += sx * _w(P, (0.80, 7.17, 0.76), (0.30, 0.35, 0.35)) * v.get("ear", 0.0) * 0.10
    # age: hollow cheeks, dropped jowls, thinner lips
    P[:, 2] -= _w(P, (0.50, 6.78, 1.32), (0.24, 0.22, 0.22)) * v.get("hollow", 0.0) * 0.10
    P[:, 1] -= _w(P, (0.34, 6.34, 1.35), (0.28, 0.16, 0.22)) * v.get("jowl", 0.0) * 0.08
    return P


def to_metres(P, height):
    S = height / _HEIGHT_UNITS
    return (P - np.array([0, FEET_Y, 0], F)) * S


# ------------------------------------------------------------------ hair/eyes
def scalp_weight(P, style="short"):
    """Soft hairline mask in model units; 1 = scalp."""
    x, y, z = P[:, 0], P[:, 1], P[:, 2]
    ax = np.abs(x)
    # hairline: high on the forehead, lower at the sides and back
    front = np.clip((z - 0.15) / 0.9, 0, 1)
    # Garis rambut: dulu 7.28 (hanya 33% ubun-ubun) sehingga rambut tampak
    # seperti kopiah. Sekarang ~59% tinggi kepala, turun di pelipis dan belakang.
    line = 6.80 + 0.22 * front - 0.12 * np.clip((ax - 0.45) / 0.4, 0, 1)
    line -= 0.42 * np.clip((-z - 0.1) / 0.6, 0, 1)
    if style == "receding":
        line += 0.20 * np.clip((ax - 0.16) / 0.40, 0, 1) * front
    elif style == "bowl":
        # potongan mangkuk: garis rambut turun rata (khas anak)
        line -= 0.30
    elif style == "fringe":
        # poni: bagian depan turun, samping tetap
        line -= 0.16 * front
    # irregular hairline (widow's peaks, temple recession)
    irregular = 0.045 * np.sin(ax * 11.0 + 1.3) + 0.028 * np.sin(z * 9.0 + 2.1) + 0.02 * np.sin(ax * 23.0)
    line += irregular
    w = smoothstep((y - line) / 0.30)
    # keep ears and face clear
    ear = np.sqrt(((ax - 0.80) / 0.26) ** 2 + ((y - 7.16) / 0.30) ** 2) < 1.0
    face = (z > 1.15) & (y < 7.62)
    w = np.where(ear, 0.0, w)
    w = np.where(face & (np.abs(y - 7.4) < 0.35) & (ax < 0.55), 0.0, w)
    return w.astype(F)


def build_hair_shell(P, N, idx, style, thickness):
    """Copy scalp triangles outward along normals; returns (pos, uv, idx, vmap)."""
    w = scalp_weight(P, style)
    keep = (w[idx] > 0.25).all(1)
    tris = idx[keep]
    if len(tris) == 0:
        return None
    used, inv = np.unique(tris.ravel(), return_inverse=True)
    nrm = compute_normals(P, idx)
    # thin at the hairline, full volume on the crown; swept slightly back
    ww = w[used]
    thick = thickness * (0.05 + 1.10 * smoothstep((ww - 0.10) / 0.62))
    pos = P[used] + nrm[used] * thick[:, None]
    # crown volume: lift and sweep back
    crown = smoothstep((ww - 0.45) / 0.55)
    pos[:, 1] += crown * thickness * 0.55
    pos[:, 2] -= thick * 0.45 + crown * 0.02
    # cylindrical UV around the head so strand textures run vertically
    cx, cz = 0.0, 0.15
    u = np.arctan2(pos[:, 0] - cx, pos[:, 2] - cz) / (2 * np.pi) + 0.5
    v = np.clip((pos[:, 1] - 6.30) / 1.55, 0, 1)
    uv = np.stack([u, v], 1)
    return pos, uv, inv.reshape(-1, 3), used, w[used]


def build_long_hair(P, style, thickness, length=0.42):
    """A curved back panel for long hair, following the skull then falling."""
    angles = np.linspace(-0.62, 0.62, 13)
    rows = []
    for i, yy in enumerate(np.linspace(0, 1, 11)):
        row = []
        for a in angles:
            t = yy
            radius = 0.92 + 0.16 * np.sin(t * 1.7)
            y = 7.55 - t * (2.9 + 2.0 * length)
            shrink = 1.0 - 0.22 * max(0, t - 0.55)
            cx = np.sin(a) * radius * shrink
            cz = 0.32 - np.cos(a) * radius * shrink * (0.85 + 0.1 * t)
            if t > 0.85:  # ends flare slightly
                cz -= 0.04
            row.append([cx, y, cz])
        rows.append(row)
    pos = np.array(rows, F).reshape(-1, 3)
    uvs = []
    for i in range(pos.shape[0] // len(angles)):
        for j in range(len(angles)):
            uvs.append([j / (len(angles) - 1) * 2.0, i / 10 * 2.2])
    uvs = np.array(uvs, F)
    idx = []
    for i in range(9):
        for j in range(len(angles) - 1):
            a = i * len(angles) + j
            b = a + len(angles)
            idx.extend([a, b, a + 1, a + 1, b, b + 1])
    return pos, uvs, np.array(idx, np.int64).reshape(-1, 3)


def eye_texture(size=256, iris="#4a2f1c", sclera="#ded6c8", vein=0.5):
    """Radial iris with limbal ring + pupil, for a disc mapped 0..1."""
    yy, xx = np.mgrid[0:size, 0:size].astype(F)
    cx = cy = size / 2
    r = np.sqrt((xx - cx) ** 2 + (yy - cy) ** 2) / (size / 2)
    ang = np.arctan2(yy - cy, xx - cx)
    fibers = 0.5 + 0.5 * np.sin(ang * 26 + np.sin(ang * 7) * 2.2 + r * 14)
    base = np.zeros((size, size, 3), F)
    iris_col = uvpaint.srgb_hex(iris)
    scl_col = uvpaint.srgb_hex(sclera)
    pupil_r = 0.24
    iris_r = 1.0
    t = np.clip((r - pupil_r) / (iris_r - pupil_r), 0, 1)
    col = iris_col[None, None, :] * (0.55 + 0.75 * fibers[..., None]) * (1 - 0.35 * t[..., None])
    # limbal ring
    ring = np.clip((r - 0.86) / 0.14, 0, 1)
    col = col * (1 - 0.6 * ring[..., None])
    base[:] = col
    pupil = r < pupil_r
    base[pupil] = 0.012
    # sclera outside the iris: not used on the disc, but kept for safety
    outside = r > 1.0
    base[outside] = scl_col[None, :] * (0.9 + 0.1 * np.sin(ang[outside] * 9))[:, None]
    rough = np.where(pupil, 0.35, 0.22) * np.ones((size, size), F)
    normal = tex.height_to_normal(0.5 + fibers * 0.06 * (r < 1.05), 1.0)
    orm = np.stack([np.ones((size, size), F) * (1 - 0.5 * pupil), rough, np.zeros((size, size), F)], -1)
    return {"base": np.clip(base, 0, 1), "normal": normal, "orm": orm}


def sclera_texture(size=256, vein=0.6):
    n = tex.fbm(size, size, 40, 4, 0.55, 4)
    base = np.tile(np.array([0.87, 0.84, 0.80], F), (size, size, 1))
    # red veins near the edges
    veinmap = np.clip((tex.fbm(size, size, 60, 4, 0.6, 9) - 0.55) * 4, 0, 1)
    base = base * (1 - veinmap[..., None] * 0.55 * vein) + np.array([0.55, 0.16, 0.14], F) * (veinmap[..., None] * 0.55 * vein)
    return {"base": np.clip(base, 0, 1), "normal": tex.height_to_normal(0.5 + n * 0.04, 1.0), "orm": tex.orm(np.ones((size, size), F) * 0.95, 0.28 + n * 0.1, np.zeros((size, size), F))}


def hair_texture(size=512, color="#1b1512", kind="straight", seed=5):
    n = tex.fbm(size, size, (2, 48), 3, 0.55, seed)
    yy, xx = np.mgrid[0:size, 0:size].astype(F)
    freq = 190 if kind != "curl" else 110
    strand = np.sin(xx / size * freq * 2 * np.pi + n * 26 + np.sin(yy / size * 30) * 1.5) * 0.5 + 0.5
    strand = strand**1.6
    clump = tex.fbm(size, size, (40, 6), 3, 0.55, seed + 3)
    col = uvpaint.srgb_hex(color)
    base = np.tile(col, (size, size, 1)) * (0.62 + 0.42 * strand[..., None] + 0.18 * clump[..., None])
    highlight = np.clip((strand * 0.6 + clump * 0.4 - 0.80) * 5, 0, 1)
    base = base + highlight[..., None] * 0.06
    height = 0.5 + strand * 0.30 + clump * 0.15
    rough = 0.50 + 0.25 * (1 - strand)
    return {"base": np.clip(base, 0, 1), "normal": tex.height_to_normal(height, 2.0), "orm": tex.orm(np.ones((size, size), F) * 0.9, rough, np.zeros((size, size), F))}


